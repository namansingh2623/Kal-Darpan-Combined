export function translate(text, language) {
  if (typeof text !== 'string') return text;
  if (language === 'hi') {
    const nearbyCount = text.match(/^(\d+) landmark(s?) within 100 km\.$/);
    if (nearbyCount) return `100 किमी के भीतर ${nearbyCount[1]} स्मारक।`;
    return hindi[text] || text;
  }
  if (language === 'ta') {
    const nearbyCount = text.match(/^(\d+) landmark(s?) within 100 km\.$/);
    if (nearbyCount) return `100 கி.மீ. சுற்றளவில் ${nearbyCount[1]} இடங்கள்.`;
    return tamil[text] || text;
  }
  return text;
}

export function useLanguage() {
  const [language, setLanguage] = useState(() => {
    try {
      const savedLanguage = localStorage.getItem('kaal-darpan-language');
      return savedLanguage === 'hi' || savedLanguage === 'ta' ? savedLanguage : 'en';
    } catch {
      return 'en';
    }
  });
  const setApplicationLanguage = useCallback((nextLanguage) => {
    setLanguage(nextLanguage);
    narrationSettings.set({ language: nextLanguage === 'ta' ? 'ta-IN' : nextLanguage === 'hi' ? 'hi-IN' : 'en' });
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    narrationSettings.set({ language: language === 'ta' ? 'ta-IN' : language === 'hi' ? 'hi-IN' : 'en' });
    try {
      localStorage.setItem('kaal-darpan-language', language);
    } catch (error) {
      console.warn('Unable to save the language preference.', error);
    }
  }, [language]);

  const t = useCallback((text) => translate(text, language), [language]);
  return { language, setLanguage: setApplicationLanguage, t };
}

export function LanguageToggle({ language, onChange, className = '' }) {
  return (
    <div className={`language-toggle ${className}`} role="group" aria-label={language === 'ta' ? 'மொழி' : language === 'hi' ? 'भाषा' : 'Language'}>
      <button type="button" lang="en" className={language === 'en' ? 'is-current' : ''} aria-pressed={language === 'en'} onClick={() => onChange('en')}>EN</button>
      <span aria-hidden="true">/</span>
      <button type="button" lang="hi" className={language === 'hi' ? 'is-current' : ''} aria-pressed={language === 'hi'} onClick={() => onChange('hi')}>हिन्दी</button>
      <span aria-hidden="true">/</span>
      <button type="button" lang="ta" className={language === 'ta' ? 'is-current' : ''} aria-pressed={language === 'ta'} onClick={() => onChange('ta')}>தமிழ்</button>
    </div>
  );
}
