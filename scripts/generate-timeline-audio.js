import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createServer } from 'vite';
import { monuments } from '../src/data.js';
import { monumentList } from '../src/viewer/monumentsData.js';
import { eventSpeech, laterHistorySpeech, monumentInfoSpeech, poiSpeech } from '../src/viewer/narrationText.js';
import { forSpeech, splitAtRequestLimit } from '../src/viewer/speech.js';
import { PRONUNCIATION_TEST } from '../src/viewer/pronunciation.js';

const supportedLanguages = ['en', 'hi-IN', 'ta-IN'];
const isVerify = process.argv.includes('--verify');
const languageOption = process.argv.find((argument) => argument.startsWith('--language='));
const languages = languageOption
  ? supportedLanguages.filter((language) => language === languageOption.slice('--language='.length))
  : isVerify ? supportedLanguages : ['hi-IN', 'ta-IN'];
const baseRate = 0.92;
const publicDir = resolve('public', 'narration');
const manifestPath = resolve(publicDir, 'manifest.json');
const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const assetPath = (text, language) => `/narration/${sha256(JSON.stringify([text, language]))}.mp3`;
const maxLength = (language) => language === 'en' ? 4500 : 1000;

function collectNarrationTexts() {
  const texts = new Set(PRONUNCIATION_TEST);
  for (const monument of monumentList) {
    for (const phase of monument.construction.phases) {
      texts.add(phase.narration || phase.description || phase.label);
    }
    for (const poi of monument.pois) texts.add(poiSpeech(poi));
    for (const event of monument.events || []) texts.add(eventSpeech(event));
    texts.add(laterHistorySpeech(monument));
    texts.add(monumentInfoSpeech(monument));
  }
  for (const monument of monuments) texts.add(monument.summary);
  return [...texts].filter(Boolean);
}

async function readExistingManifest() {
  try {
    return JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return { clips: {} };
    throw error;
  }
}

async function verifyBundle(clips) {
  let missingTotal = 0;
  for (const language of languages) {
    const expected = new Set();
    for (const rawText of collectNarrationTexts()) {
      const text = forSpeech(rawText);
      for (const chunk of splitAtRequestLimit(text, maxLength(language))) {
        expected.add(JSON.stringify([chunk, language]));
      }
    }
    let missing = 0;
    for (const key of expected) {
      const url = clips[key];
      if (!url) {
        missing += 1;
        continue;
      }
      try {
        await readFile(resolve('public', url.slice(1)));
      } catch {
        missing += 1;
      }
    }
    missingTotal += missing;
    console.log(`${language}: ${expected.size - missing}/${expected.size} expected clips are present.`);
  }
  if (missingTotal) {
    console.error(`${missingTotal} required narration clips are missing.`);
    process.exitCode = 1;
  }
}

async function main() {
  if (languageOption && !languages.length) throw new Error('Use --language=en, --language=hi-IN, or --language=ta-IN.');
  await mkdir(publicDir, { recursive: true });
  const existing = await readExistingManifest();
  const clips = { ...existing.clips };
  if (isVerify) {
    await verifyBundle(clips);
    return;
  }
  const queue = [];
  for (const rawText of collectNarrationTexts()) {
    const text = forSpeech(rawText);
    for (const language of languages) {
      for (const chunk of splitAtRequestLimit(text, maxLength(language))) {
        const key = JSON.stringify([chunk, language]);
        const url = assetPath(chunk, language);
        if (clips[key]) continue;
        queue.push({ key, text: chunk, language, url });
      }
    }
  }

  if (process.argv.includes('--dry-run')) {
    for (const language of languages) {
      const pending = queue.filter((clip) => clip.language === language);
      console.log(`${language}: ${pending.length} clips, ${pending.reduce((total, clip) => total + clip.text.length, 0)} characters to generate.`);
    }
    return;
  }

  if (!queue.length) {
    console.log('All timeline narration clips are already bundled.');
    return;
  }
  if (languages.includes('en')) {
    throw new Error('English narration is provided by the bundled audio files and is not generated by a web API.');
  }

  const server = await createServer({
    configFile: resolve('vite.config.js'),
    server: { host: '127.0.0.1', port: 5175, strictPort: true },
    optimizeDeps: { noDiscovery: true, include: [] },
  });

  let completed = 0;
  let stopped = false;
  let failure = null;
  try {
    await server.listen();
    let next = 0;
    const worker = async () => {
      while (!stopped && next < queue.length) {
        const clip = queue[next++];
        const diskPath = resolve('public', clip.url.slice(1));
        try {
          const response = await fetch('http://127.0.0.1:5175/api/narration', {
            method: 'POST',
            headers: {
              'Content-Type': 'application/json',
              Origin: 'http://127.0.0.1:5175',
            },
            body: JSON.stringify({ text: clip.text, language: clip.language, rate: baseRate }),
          });
          if (!response.ok) {
            const result = await response.json().catch(() => ({}));
            throw new Error(`${clip.language}: ${result.error || `Narration failed (${response.status}).`}`);
          }
          const audio = Buffer.from(await response.arrayBuffer());
          if (!audio.length || !response.headers.get('content-type')?.includes('audio')) {
            throw new Error(`${clip.language}: narration service returned an invalid audio file.`);
          }
          await writeFile(diskPath, audio);
          clips[clip.key] = clip.url;
          completed += 1;
          console.log(`Generated ${completed}/${queue.length} bundled clips (${clip.language}).`);
        } catch (error) {
          failure ||= error;
          stopped = true;
        }
      }
    };
    await Promise.all([worker(), worker()]);
  } finally {
    await server.close();
  }

  await writeFile(manifestPath, `${JSON.stringify({ clips }, null, 2)}\n`);
  if (failure) {
    console.error(`Stopped after ${completed} new clips. Successfully generated audio remains bundled; check the Sarvam provider configuration and try again. ${failure.message}`);
    process.exitCode = 1;
    return;
  }
  console.log(`Bundled ${completed} new clips. Future playback uses the project audio files instead of generating them again.`);
}

main().catch((error) => {
  console.error(`Could not bundle timeline narration: ${error.message}`);
  process.exitCode = 1;
});
